const segments = new Intl.Segmenter("ar", { granularity: "grapheme" });
export function localCardName(name: string): string {
  return Array.from(segments.segment(name), ({ segment }) =>
    Array.from(segment).every(char => {
      const point = char.codePointAt(0)!;
      return LOCAL_GLYPH_RANGES.some(([start, end]) => point >= start && point <= end);
    }) ? segment.replaceAll("[", "[[").replaceAll("]", "]]")
      : `[${Array.from(segment, char => `U+${char.codePointAt(0)!.toString(16).toUpperCase()}`).join(" ")}]`).join("");
}

/**
 * Satori currently shapes Arabic words but does not reorder whitespace-separated
 * words with CSS direction:rtl. Explicit RTL flex runs preserve logical reading
 * order; contiguous non-Arabic words stay together in their normal LTR order.
 */
export function cardTextRuns(text: string): string[] {
  const runs: string[] = [];
  let previousWasLtr = false;
  for (const word of text.trim().split(/\s+/u).filter(Boolean)) {
    const ltr = !/\p{Script=Arabic}/u.test(word);
    if (ltr && previousWasLtr) runs[runs.length - 1] += ` ${word}`;
    else runs.push(word);
    previousWasLtr = ltr;
  }
  return runs;
}
