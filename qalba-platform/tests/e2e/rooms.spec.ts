import { expect, test } from "@playwright/test";

test("host opens a room and guest joins, readies and answers live", async ({ browser, page }) => {
  test.skip(!process.env.E2E_DATABASE_URL, "Requires migrated PostgreSQL");
  await page.goto("/register");
  await page.getByLabel("الاسم").fill("مضيف الغرفة");
  await page.getByLabel("البريد الإلكتروني").fill(`room-${Date.now()}@example.test`);
  await page.getByLabel("كلمة المرور").fill("room-password-12345");
  await page.getByRole("button", { name: "إنشاء الحساب" }).click();
  await page.getByRole("link", { name: "ابدأ لوحة التحدي" }).click();
  const categories = page.getByRole("checkbox");
  for (let index = 0; index < 6; index++) await categories.nth(index).check();
  await page.getByRole("button", { name: "جهّز اللوحة" }).click();
  await page.getByRole("button", { name: "أنشئ غرفة برمز" }).click();
  const code = await page.locator(".room-code").innerText();
  expect(code).toMatch(/^[A-HJ-NP-Z2-9]{6}$/);
  const guestContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const guest = await guestContext.newPage();
  await guest.goto(`/join?code=${code}`);
  await expect(guest.getByLabel("اسمك في اللعب")).toBeVisible();
  await guest.getByLabel("اسمك في اللعب").fill("ضيفة البرق");
  await guest.getByRole("button", { name: "انضم إلى الغرفة" }).click();
  await expect(guest).toHaveURL(new RegExp(`/rooms/${code}$`));
  await guest.getByRole("button", { name: "أنا جاهز" }).click();
  await expect(page.getByText("1 لاعب في الغرفة · 1 جاهزون")).toBeVisible();
  await page.getByRole("button", { name: "ابدأ المباراة" }).click();
  await page.getByRole("button", { name: "معلومات عامة 200" }).click();
  await expect(guest.locator(".room-question h2")).toBeVisible();
  await guest.getByLabel("إجابتك للمضيف").fill("إجابة من الجوال");
  await guest.getByRole("button", { name: "أرسل" }).click();
  await expect(page.getByText("ضيفة البرق: إجابة من الجوال")).toBeVisible();
  await expect(guest.locator("body")).toHaveJSProperty("scrollWidth", 390);
  await guest.reload();
  await expect(guest.getByRole("button", { name: "وصلت إجابتك" })).toBeDisabled();
  await expect(guest.getByRole("button", { name: /صحيح/ })).toHaveCount(0);
  await page.getByRole("button", { name: "اكشف الإجابة" }).click();
  await expect(guest.locator(".answer-reveal")).toBeVisible();
  await guestContext.close();
});
