import { expect, test } from "@playwright/test";

test("host configures and plays a round, then refreshes on desktop and mobile", async ({ page }) => {
  test.skip(!process.env.E2E_DATABASE_URL, "Requires migrated PostgreSQL via E2E_DATABASE_URL");
  const email = `board-${Date.now()}@example.test`;
  await page.goto("/register");
  await page.getByLabel("الاسم").fill("مضيفة التحدي");
  await page.getByLabel("البريد الإلكتروني").fill(email);
  await page.getByLabel("كلمة المرور").fill("board-password-12345");
  await page.getByRole("button", { name: "إنشاء الحساب" }).click();
  await expect(page).toHaveURL(/\/games$/);
  await expect(page.getByRole("link", { name: /رصيدك: 3 ألعاب/ })).toBeVisible();
  await page.getByRole("link", { name: "ابدأ لوحة التحدي" }).click();
  await expect(page.getByRole("heading", { name: "جهّزوا جمعتكم" })).toBeVisible();
  const categories = page.getByRole("checkbox");
  await expect(categories).toHaveCount(6);
  for (let index = 0; index < 6; index++) await categories.nth(index).check();
  await page.getByRole("button", { name: "جهّز اللوحة" }).click();
  await expect(page).toHaveURL(/\/play\/[^/]+$/);
  await page.getByRole("button", { name: "ابدأ المباراة" }).click();
  await expect(page.getByRole("heading", { name: "اختاروا السؤال التالي" })).toBeVisible();
  const account = await page.context().newPage();
  await account.goto("/profile");
  await expect(account.locator(".credit-panel .stat")).toHaveText("2");
  await expect(account.getByRole("heading", { name: "جلساتك" })).toBeVisible();
  await account.reload();
  await expect(account.locator(".credit-panel .stat")).toHaveText("2");
  await account.close();
  await page.getByRole("button", { name: "معلومات عامة 200" }).click();
  await expect(page.getByRole("button", { name: "اكشف الإجابة" })).toBeVisible();
  await page.getByRole("button", { name: "بلّغ عن السؤال" }).click();
  await page.getByLabel("السبب").selectOption("UNCLEAR");
  await page.getByLabel("تفاصيل إضافية (اختياري)").fill("العبارة غير واضحة");
  await page.getByRole("button", { name: "إرسال البلاغ" }).click();
  await expect(page.getByRole("status")).toContainText("وصل بلاغك");
  if (process.env.CAPTURE_QA) {
    await page.setViewportSize({ width: 1920, height: 1080 });
    await page.screenshot({ path: "/tmp/qalba-host-tv.png", fullPage: true });
  }
  await page.getByRole("button", { name: "شغّل المؤقت" }).click();
  await page.getByRole("button", { name: "اكشف الإجابة" }).click();
  await expect(page.locator(".answer-reveal")).toBeVisible();
  await page.getByRole("button", { name: /صحيح/ }).click();
  await expect(page.getByRole("button", { name: "معلومات عامة 200 مستخدم" })).toBeDisabled();
  const completed = page.getByRole("button", { name: "معلومات عامة 200 مستخدم" });
  await expect(completed).toHaveText("✓");
  expect(await completed.evaluate((element) => getComputedStyle(element, "::after").content)).toBe("none");
  await page.reload();
  await expect(page.getByRole("button", { name: "معلومات عامة 200 مستخدم" })).toBeDisabled();
  await expect(page.getByRole("button", { name: "تراجع عن آخر إجراء" })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator("body")).toHaveJSProperty("scrollWidth", 390);
  await expect(page.getByRole("heading", { name: "اختاروا السؤال التالي" })).toBeVisible();
  await page.getByRole("button", { name: "فتح شاشة العرض" }).click();
  const [display] = await Promise.all([page.context().waitForEvent("page"), page.getByRole("dialog", { name: "شاشة العرض" }).getByRole("button", { name: "فتح العرض في هذا الجهاز" }).click()]);
  await page.getByRole("dialog", { name: "شاشة العرض" }).getByRole("button", { name: "إغلاق" }).click();
  await expect(display).toHaveURL(/\/display\/[^?]+\?token=/);
  await display.setViewportSize({ width: 1920, height: 1080 });
  await expect(display.getByRole("heading", { name: "اختاروا السؤال التالي" })).toBeVisible();
  if (process.env.CAPTURE_QA) {
    await display.screenshot({ path: "/tmp/qalba-display-tv.png", fullPage: true });
    await page.getByRole("button", { name: "السعودية 200" }).click();
    await expect(display.getByText("دور فريق الموج")).toBeVisible();
    await expect.poll(() => display.evaluate(() => document.body.scrollHeight)).toBeLessThanOrEqual(1080);
    await display.screenshot({ path: "/tmp/qalba-display-question-tv.png", fullPage: true });
    await page.getByRole("button", { name: "تخطي" }).click();
  }
  await expect(display.locator("body")).toHaveJSProperty("scrollWidth", 1920);
  await expect(display.getByRole("button", { name: /صحيح/ })).toHaveCount(0);
  await display.getByRole("button", { name: "ملء الشاشة" }).click();
  await expect.poll(() => display.evaluate(() => Boolean(document.fullscreenElement))).toBe(true);
  await page.getByRole("button", { name: "إيقاف المباراة مؤقتًا" }).click();
  await expect(display.getByText("المباراة متوقفة", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "أضف نقاطًا إلى فريق البرق" }).click();
  await expect(display.locator(".display-team").filter({ hasText: "فريق البرق" })).toContainText("300");
  await page.getByRole("button", { name: "استئناف المباراة" }).click();
  page.once("dialog", (dialog) => dialog.accept());
  await page.getByRole("button", { name: "إنهاء المباراة" }).click();
  await expect(display.getByRole("heading", { name: "الفائز: فريق البرق" })).toBeVisible();
  // The intentional completed-match redesign collapses post-game score corrections.
  await expect(page.locator(".score-editor-details")).toBeVisible();
  await page.locator(".score-editor-details summary").click();
  await expect(page.locator(".score-editor-details")).toHaveAttribute("open", "");
  await page.getByRole("button", { name: "أضف نقاطًا إلى فريق الموج" }).click();
  await display.reload();
  await expect(display.locator(".display-team").filter({ hasText: "فريق الموج" }).locator("strong")).toHaveText("100");
  await page.getByRole("button", { name: "تراجع عن آخر تغيير" }).click();
  await display.reload();
  await expect(display.locator(".display-team").filter({ hasText: "فريق الموج" }).locator("strong")).toHaveText("0");
});
